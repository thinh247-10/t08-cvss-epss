"""Independent fixtures from FIRST CVSS 3.1 sections 7.1/7.4 and Appendix A.

Expected scores are fixed from a Decimal worksheet using FIRST constants,
not generated by the scorer under test. See reports/p2_scorer_check.md.
"""

import unittest

from src.collect.nvd_collector import parse_base_vector
from src.environmental.cvss_base import calculate_base_score, roundup


SCORE_CASES = (
    ("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H", 9.8),
    ("CVSS:3.1/AV:N/AC:L/PR:L/UI:N/S:U/C:H/I:H/A:H", 8.8),
    ("CVSS:3.1/AV:N/AC:L/PR:H/UI:N/S:U/C:H/I:H/A:H", 7.2),
    ("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:C/C:H/I:H/A:H", 10.0),
    ("CVSS:3.1/AV:N/AC:L/PR:L/UI:N/S:C/C:H/I:H/A:H", 9.9),
    ("CVSS:3.1/AV:N/AC:L/PR:H/UI:N/S:C/C:H/I:H/A:H", 9.1),
    ("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:N/I:N/A:N", 0.0),
    ("CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:C/C:N/I:N/A:N", 0.0),
)


class CVSSChecks(unittest.TestCase):
    def test_scope_and_all_privilege_branches(self):
        for vector, expected in SCORE_CASES[:6]:
            with self.subTest(vector=vector):
                self.assertEqual(calculate_base_score(vector), expected)

    def test_zero_impact_for_both_scopes(self):
        for vector, expected in SCORE_CASES[6:]:
            with self.subTest(vector=vector):
                self.assertEqual(calculate_base_score(vector), expected)

    def test_metric_order_does_not_change_score(self):
        vector = SCORE_CASES[2][0]
        shuffled = "CVSS:3.1/" + "/".join(reversed(vector.split("/")[1:]))
        self.assertEqual(parse_base_vector(shuffled), parse_base_vector(vector))
        self.assertEqual(calculate_base_score(shuffled), 7.2)

    def test_roundup_noise_and_one_decimal_boundaries(self):
        cases = ((0.1 + 0.2, 0.3), (4.0, 4.0), (4.02, 4.1),
                 (9.00096434086808, 9.1), (0.0, 0.0), (10.0, 10.0))
        for value, expected in cases:
            with self.subTest(value=value):
                self.assertEqual(roundup(value), expected)

    def test_missing_duplicate_unknown_and_bad_values_are_rejected(self):
        base = SCORE_CASES[0][0]
        invalid = (base.replace("/A:H", ""), base.replace("AC:L", "AV:N"),
                   base.replace("AV:N", "ZZ:N"), base.replace("PR:N", "PR:X"),
                   base.replace("UI:N", "UI:False"), base.replace("C:H", "C:h"),
                   base + "/AV:N", base + "/", base.replace("AV:N", "AV:N:extra"))
        for vector in invalid:
            with self.subTest(vector=vector):
                self.assertIsNone(parse_base_vector(vector))
                with self.assertRaises(ValueError):
                    calculate_base_score(vector)

    def test_versions_types_and_non_base_metrics_are_rejected(self):
        base = SCORE_CASES[0][0]
        invalid = (None, 98, {}, "", base.replace("3.1", "3.0"),
                   base.replace("3.1", "4.0"), base + "/E:X", base + "/CR:H",
                   base + "/MAV:N")
        for vector in invalid:
            with self.subTest(vector=vector):
                self.assertIsNone(parse_base_vector(vector))
                with self.assertRaises(ValueError):
                    calculate_base_score(vector)


if __name__ == "__main__":
    unittest.main()
